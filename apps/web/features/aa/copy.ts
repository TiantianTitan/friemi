export function getAaStatusLabel(locale: string, status: string) {
  const copy = getAaCopy(locale);
  const labels: Record<string, string> = {
    PENDING_REVIEW: copy.pendingReview,
    PENDING_CONFIRMATION: copy.pendingConfirmation,
    REJECTED: copy.rejected,
    DISPUTED: copy.disputed,
    VOIDED: copy.voided,
    POSTED: copy.posted,
  };
  return labels[status] ?? status;
}
